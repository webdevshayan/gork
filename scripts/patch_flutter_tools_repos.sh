#!/usr/bin/env bash
# build-box — make the INCLUDED flutter_tools gradle build rate-limit-proof.
#
# Why: the app's settings.gradle.kts already puts the Aliyun mirrors before
# mavenCentral (repo.maven.apache.org 429s this network — Movement 30). But
# gradle resolves Kotlin build tools inside the INCLUDED build
# $FLUTTER_ROOT/packages/flutter_tools/gradle, and included builds do NOT
# inherit the app's repositories. Upstream flutter ships that file with
# google() + mavenCentral() only, so `assembleRelease` dies with a 429 on
# kotlin-build-tools-impl before compiling anything.
#
# What this does: insert the Aliyun central/public mirrors before
# mavenCentral in that settings file. Idempotent — safe to run on every
# toolchain rebuild. The file is regenerated by every flutter install, so
# run this once after installing/upgrading the SDK (see docs/BUILD-ENV.md).
#
# Usage: scripts/patch_flutter_tools_repos.sh
set -euo pipefail

FLUTTER_ROOT="${FLUTTER_ROOT:-$(command -v flutter >/dev/null 2>&1 \
  && dirname "$(dirname "$(command -v flutter)")")}"
if [ -z "$FLUTTER_ROOT" ] || [ ! -d "$FLUTTER_ROOT" ]; then
  echo "FATAL: cannot locate the flutter SDK — set FLUTTER_ROOT" >&2
  exit 1
fi

TARGET="$FLUTTER_ROOT/packages/flutter_tools/gradle/settings.gradle.kts"
if [ ! -f "$TARGET" ]; then
  echo "FATAL: $TARGET not found — is FLUTTER_ROOT a flutter checkout?" >&2
  exit 1
fi

if grep -q 'maven.aliyun.com' "$TARGET"; then
  echo "already patched: $TARGET resolves via Aliyun before mavenCentral"
  exit 0
fi

cp "$TARGET" "$TARGET.bak-gork"
python3 - "$TARGET" <<'PY'
import sys
path = sys.argv[1]
with open(path) as f:
    text = f.read()
needle = "    repositories {\n        google()\n        mavenCentral()\n    }"
replacement = (
    "    repositories {\n"
    "        google()\n"
    "        // build-box: repo.maven.apache.org 429s this network — Aliyun\n"
    "        // mirrors before mavenCentral (scripts/patch_flutter_tools_repos.sh).\n"
    "        maven(\"https://maven.aliyun.com/repository/central\")\n"
    "        maven(\"https://maven.aliyun.com/repository/public\")\n"
    "        mavenCentral()\n"
    "    }"
)
if needle not in text:
    sys.exit("FATAL: upstream repositories block not found — flutter version changed; patch manually")
with open(path, "w") as f:
    f.write(text.replace(needle, replacement, 1))
print(f"patched: {path} — Aliyun mirrors now precede mavenCentral")
PY
echo "backup at $TARGET.bak-gork"
